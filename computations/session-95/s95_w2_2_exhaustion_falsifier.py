def HH2_matrix_block(n: int) -> tuple:
    """dim HH^2(M_n(C), M_n(C)) = dim(ker d^2) - dim(im d^1).
    Hochschild complex with coefficients in A=M_n:
      C^1=Hom(A,A) dim N^2; C^2=Hom(A x A,A) dim N^3; C^3 dim N^4.
      (d^1 f)(a,b) = a f(b) - f(ab) + f(a) b
      (d^2 g)(a,b,c) = a g(b,c) - g(ab,c) + g(a,bc) - g(a,b) c
    Returns (HH2_dim, dimZ2, dimB2). For semisimple M_n: HH^2 = 0 (Gerstenhaber rigidity).
    EXACT Fraction ranks."""
    N = n * n  # (local)
    units = matrix_units(n)  # (local)
    F0, F1 = Fraction(0), Fraction(1)

    # ---- d^1 : C^1 -> C^2  (matrix; rank = dim B^2) ----
    in1 = N * N  # (local) — entries of F (f(E_q)= sum_p F[p][q] E_p)

    def colF(p, q):
        return q * N + p

    def idx2(a, b, r):
        return (a * N + b) * N + r

    d1_rows = {}  # (local) — accumulate by output index -> dict col->coeff
    for a in range(N):
        ia, ja = units[a]
        for b in range(N):
            ib, jb = units[b]
            prod = matmul_units(ia, ja, ib, jb, n)  # (E_a E_b) coord
            # term1: E_a f(E_b) = sum_p F[p][b] (E_a E_p)
            for p in range(N):
                ip, jp = units[p]
                c = matmul_units(ia, ja, ip, jp, n)
                if c is not None:
                    key = idx2(a, b, c)
                    d1_rows.setdefault(key, {})
                    d1_rows[key][colF(p, b)] = d1_rows[key].get(colF(p, b), F0) + F1
            # term2: -f(E_a E_b) = -F[p][prod] E_p  (component p)
            if prod is not None:
                for p in range(N):
                    key = idx2(a, b, p)
                    d1_rows.setdefault(key, {})
                    d1_rows[key][colF(p, prod)] = d1_rows[key].get(colF(p, prod), F0) - F1
            # term3: f(E_a) E_b = sum_p F[p][a] (E_p E_b)
            for p in range(N):
                ip, jp = units[p]
                c = matmul_units(ip, jp, ib, jb, n)
                if c is not None:
                    key = idx2(a, b, c)
                    d1_rows.setdefault(key, {})
                    d1_rows[key][colF(p, a)] = d1_rows[key].get(colF(p, a), F0) + F1
    # densify d1 rows
    d1_dense = []  # (local)
    for key, dd in d1_rows.items():
        row = [F0] * in1
        for cc, vv in dd.items():
            row[cc] = vv
        if any(x != 0 for x in row):
            d1_dense.append(row)
    dimB2 = rref_rank_fraction(d1_dense)  # (local)

    # ---- d^2 : C^2 -> C^3  (rank => dim Z^2 = N^3 - rank) ----
    in2 = N * N * N  # (local)

    def colg(a, b, r):
        return (a * N + b) * N + r

    def idx3(a, b, c, r):
        return ((a * N + b) * N + c) * N + r

    d2_rows = {}  # (local)
    for a in range(N):
        ia, ja = units[a]
        for b in range(N):
            ib, jb = units[b]
            prod_ab = matmul_units(ia, ja, ib, jb, n)  # E_a E_b coord
            for c in range(N):
                ic, jc = units[c]
                prod_bc = matmul_units(ib, jb, ic, jc, n)  # E_b E_c coord
                # term1: E_a g(E_b,E_c) = sum_s g[b][c]_s (E_a E_s)
                for s in range(N):
                    isx, jsx = units[s]
                    cc = matmul_units(ia, ja, isx, jsx, n)
                    if cc is not None:
                        key = idx3(a, b, c, cc)
                        d2_rows.setdefault(key, {})
                        d2_rows[key][colg(b, c, s)] = d2_rows[key].get(colg(b, c, s), F0) + F1
                # term2: -g(E_a E_b, E_c) = -g(prod_ab, c) (component r each)
                if prod_ab is not None:
                    for r in range(N):
                        key = idx3(a, b, c, r)
                        d2_rows.setdefault(key, {})
                        d2_rows[key][colg(prod_ab, c, r)] = d2_rows[key].get(colg(prod_ab, c, r), F0) - F1
                # term3: +g(E_a, E_b E_c) = +g(a, prod_bc)
                if prod_bc is not None:
                    for r in range(N):
                        key = idx3(a, b, c, r)
                        d2_rows.setdefault(key, {})
                        d2_rows[key][colg(a, prod_bc, r)] = d2_rows[key].get(colg(a, prod_bc, r), F0) + F1
                # term4: -g(E_a,E_b) E_c = -sum_s g[a][b]_s (E_s E_c)
                for s in range(N):
                    isx, jsx = units[s]
                    cc = matmul_units(isx, jsx, ic, jc, n)
                    if cc is not None:
                        key = idx3(a, b, c, cc)
                        d2_rows.setdefault(key, {})
                        d2_rows[key][colg(a, b, s)] = d2_rows[key].get(colg(a, b, s), F0) - F1
    d2_dense = []  # (local)
    for key, dd in d2_rows.items():
        row = [F0] * in2
        for cc, vv in dd.items():
            row[cc] = vv
        if any(x != 0 for x in row):
            d2_dense.append(row)
    rank_d2 = rref_rank_fraction(d2_dense)  # (local)
    dimZ2 = in2 - rank_d2  # (local)
    return dimZ2 - dimB2, dimZ2, dimB2


