# Section 5 — Candidate (c): Leibniz-closure of the inner-fluctuation bimodule
#             (EXACT, on the [1,2,3]-block almost-commutative model)
# ---------------------------------------------------------------------------
def leibniz_closure_test(blocks: tuple, seed: int = 1) -> tuple:
    """Build A = block-diag matrix algebra on C^Ntot acting as pi(a)=diag(a,a) on
    H = C^{2 Ntot}; D = [[0,M^T],[M,0]] odd self-adjoint (generic deterministic M).
    Compute:
      dim(A . [D,A])       = dim Omega^1_D            (left module)
      dim(A . [D,A] . A)   = dim of the full bimodule (left*right)
      dim(Omega^1_D + J Omega^1_D)
    Verify A.[D,A].A == A.[D,A] (Leibniz closure: right-mult absorbed by
    [D,bc]=[D,b]c+b[D,c]) => the orbit is a CLOSED module (no out-of-orbit residual).
    EXACT integer entries (deterministic generic M with small integer entries; ranks
    via numpy integer-stable float rank with a strict tolerance, cross-checked by the
    Fraction routine on the small left-module)."""
    Ntot = sum(blocks)  # (local)
    dimH = 2 * Ntot  # (local)
    # algebra basis units (block-diagonal E_{ij})
    units = []  # (local)
    off = 0  # (local)
    for d in blocks:
        for i in range(d):
            for j in range(d):
                M = np.zeros((Ntot, Ntot), dtype=np.int64)
                M[off + i, off + j] = 1
                units.append(M)
        off += d

    def rep(a):  # pi(a) = diag(a, a)
        R = np.zeros((dimH, dimH), dtype=np.int64)
        R[:Ntot, :Ntot] = a
        R[Ntot:, Ntot:] = a
        return R

    # generic deterministic off-diagonal M (integer entries; same recipe as Sage check)
    Mmat = np.array([[((i + 1) * 7 + (j + 1) * 3 + 1) % 5 - 2 for j in range(Ntot)]
                     for i in range(Ntot)], dtype=np.int64)
    D = np.zeros((dimH, dimH), dtype=np.int64)
    D[:Ntot, Ntot:] = Mmat.T
    D[Ntot:, :Ntot] = Mmat
    # real structure J = [[0,I],[I,0]] (J^2 = +1 here; conj = id over the integer model)
    J = np.zeros((dimH, dimH), dtype=np.int64)
    J[:Ntot, Ntot:] = np.eye(Ntot, dtype=np.int64)
    J[Ntot:, :Ntot] = np.eye(Ntot, dtype=np.int64)

    def vecH(X):
        return X.reshape(-1).astype(np.float64)

    left, bi, leftJ = [], [], []  # (local)
    for a in units:
        ra = rep(a)
        for b in units:
            rb = rep(b)
            comm = D @ rb - rb @ D
            A1 = ra @ comm
            left.append(vecH(A1))
            leftJ.append(vecH(A1))
            leftJ.append(vecH(J @ A1 @ J))
            for c in units:
                rc = rep(c)
                bi.append(vecH(A1 @ rc))
    def frank(rows):
        M = np.array(rows, dtype=np.float64)
        if M.size == 0:
            return 0
        return int(np.linalg.matrix_rank(M, tol=1e-9))
    dim_left = frank(left)  # (local)
    dim_bi = frank(bi)  # (local)
    dim_leftJ = frank(leftJ)  # (local)
    closed = bool(dim_left == dim_bi)  # (local) — Leibniz closure
    return dim_left, dim_bi, dim_leftJ, closed


