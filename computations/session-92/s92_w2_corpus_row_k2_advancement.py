def build_full_corpus_text(current_text: str,
                           instance_2_text: str) -> str:
    """Splice the Instance #2 block into the §10 section of the corpus.

    Append the Instance #2 block AFTER the existing Instance #1 content
    and BEFORE the section-10 closing "---" + the §11 heading. The
    splice point is the first "---" line that appears after the §10
    heading. Instance #2 is inserted before that closing rule.
    """
    sec_10_idx = current_text.find(SEC_10_HEADING_MARKER)
    if sec_10_idx < 0:
        raise RuntimeError(
            f"§10 heading not found in corpus (marker="
            f"{SEC_10_HEADING_MARKER!r})"
        )

    sec_11_idx = current_text.find(SEC_11_HEADING_MARKER, sec_10_idx)
    if sec_11_idx < 0:
        raise RuntimeError(
            f"§11 heading not found after §10 in corpus (marker="
            f"{SEC_11_HEADING_MARKER!r})"
        )

    # Find the closing "---" before §11 (block separator for §10)
    sec_10_block = current_text[sec_10_idx:sec_11_idx]  # (local)
    closing_rule = "\n---\n"  # (local)
    rule_pos_rel = sec_10_block.rfind(closing_rule)
    if rule_pos_rel < 0:
        raise RuntimeError(
            "Closing '---' separator not found between §10 and §11"
        )

    rule_pos_abs = sec_10_idx + rule_pos_rel  # (local)
    # Insert instance_2_text BEFORE the closing "\n---\n"
    new_text = (
        current_text[:rule_pos_abs] +
        "\n" +
        instance_2_text +
        current_text[rule_pos_abs:]
    )  # (local)
    return new_text


def verify_section_matches(written_text: str,
                           instance_2_text: str,
                           expected_sha: str) -> dict:
    """Re-read the written corpus text + verify the Instance #2 block is
    present with the expected SHA-256, with all 6 PASS predicates.

    Returns a dict of predicate evaluations.
    """
    result = {}  # (local)

    # Predicate (a): §10 Instance #2 block present in file
    instance_2_header_re = re.compile(
        r"^####\s+Instance\s+#2\s+—\s+S91\s+W9-11\s+bit-precision\s+"
        r"scheme-INDEPENDENCE\s+audit\s+on\s+§VII\.AQ",
        re.MULTILINE,
    )
    predicate_a = bool(instance_2_header_re.search(written_text))
    result["predicate_a_block_present"] = predicate_a

    # Predicate (b): cites S91 W9-11 audit_sha256
    predicate_b = S91_W9_11_AUDIT_SHA in written_text
    result["predicate_b_cites_s91_w9_11_audit_sha"] = predicate_b

    # Predicate (c): declares K_pre=1, K_post=2 explicitly
    has_k_pre = ("K_pre=1" in written_text) or ("K_pre = 1" in written_text)
    has_k_post = ("K_post=2" in written_text) or ("K_post = 2" in written_text)
    predicate_c = has_k_pre and has_k_post
    result["predicate_c_K_pre_K_post_declared"] = predicate_c

    # Predicate (d): three-axis structural-independence reasoning block
    # Look for axis (a), (b), (c) labels with the canonical
    # discriminator phrases
    has_axis_a = (
        "bit-identity vs threshold predicate" in written_text or
        "Axis (a) — substrate-IS observable distinctness" in written_text
    )
    has_axis_b = (
        "cross-pin-anchor vs discriminator-gate" in written_text or
        "Axis (b) — empirical regime distinctness" in written_text
    )
    has_axis_c = (
        "machine-precision vs < 1e-3" in written_text or
        "Axis (c) — outcome strength distinctness" in written_text
    )
    predicate_d = has_axis_a and has_axis_b and has_axis_c
    result["predicate_d_three_axis_reasoning"] = predicate_d
    result["predicate_d_has_axis_a"] = has_axis_a
    result["predicate_d_has_axis_b"] = has_axis_b
    result["predicate_d_has_axis_c"] = has_axis_c

    # Predicate (e): substantive_line_count of Instance #2 block >= 15
    match_header = instance_2_header_re.search(written_text)
    instance_2_line_count = 0  # (local)
    instance_2_block_extracted = ""  # (local)
    if match_header:
        start = match_header.start()
        # Find next "####" header OR next "## " section OR "---"
        # whichever comes first
        remainder = written_text[start + 4:]  # skip past "####"
        end_candidates = []  # (local)
        # Next "####" instance header
        next_inst = re.search(r"^####\s", remainder, re.MULTILINE)
        if next_inst:
            end_candidates.append(next_inst.start())
        # Next "## §" heading
        next_sec = re.search(r"^##\s+§", remainder, re.MULTILINE)
        if next_sec:
            end_candidates.append(next_sec.start())
        # Next horizontal rule "---" on its own line
        next_rule = re.search(r"^---\s*$", remainder, re.MULTILINE)
        if next_rule:
            end_candidates.append(next_rule.start())
        if end_candidates:
            end = start + 4 + min(end_candidates)
        else:
            end = len(written_text)
        instance_2_block_extracted = written_text[start:end]
        # Count non-blank substantive lines
        instance_2_line_count = sum(
            1
            for line in instance_2_block_extracted.splitlines()
            if line.strip()
        )
    predicate_e = instance_2_line_count >= 15
    result["predicate_e_substantive_line_count"] = predicate_e
    result["instance_2_line_count"] = int(instance_2_line_count)

    # Predicate (f): content_sha256 of Instance #2 block matches expected
    actual_sha = sha256_of_text(instance_2_block_extracted)
    predicate_f = actual_sha == expected_sha
    result["predicate_f_content_sha_matches"] = predicate_f
    result["instance_2_block_actual_sha256"] = actual_sha
    result["instance_2_block_expected_sha256"] = expected_sha

    # Conjunction of 6 predicates
    all_pass = (
        predicate_a and predicate_b and predicate_c and
        predicate_d and predicate_e and predicate_f
    )
    result["all_6_predicates_pass"] = all_pass

    return result


