def compute_dual_sha(script_path: Path, pins: dict,
                     promotion_text: str):
    """Compute (audit_sha256, content_sha256) per the S84+ dual-SHA
    schema.

    audit_sha256   = sha256( bytes(script) || pinmap_json
                              || promotion_text_bytes )
    content_sha256 = sha256( bytes(script) )
    """
    script_bytes = b""  # (local)
    try:
        script_bytes = script_path.read_bytes()
    except OSError:
        pass

    pinmap_json = json.dumps(
        dict(sorted(pins.items())),
        separators=(",", ":"),
        sort_keys=True,
    ).encode("utf-8")  # (local)

    h_audit = hashlib.sha256()
    h_audit.update(script_bytes)
    h_audit.update(pinmap_json)
    h_audit.update(promotion_text.encode("utf-8"))
    audit = h_audit.hexdigest()  # (local)

    h_content = hashlib.sha256()
    h_content.update(script_bytes)
    content = h_content.hexdigest()  # (local)

    return audit, content


