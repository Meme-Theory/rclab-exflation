def _section_bounds(wp_text: str, anchor_start: str,
                    section_terminator: str = "\n---\n") -> tuple:
    """Locate the §W3-2 section bounds in the WP file. Returns
    (sec_start, sec_end) absolute character offsets. The section runs
    from `anchor_start` (a unique header line) through the next
    `section_terminator` (default = horizontal rule that closes the
    section in our WP convention).
    """
    sec_start = wp_text.find(anchor_start)
    if sec_start < 0:
        raise RuntimeError(
            f"§W3-2 header anchor not found in WP "
            f"(anchor={anchor_start!r})"
        )
    # Find the next "---" horizontal rule AFTER the section header
    after_header = sec_start + len(anchor_start)
    sec_end_rel = wp_text.find(section_terminator, after_header)
    if sec_end_rel < 0:
        # No closing rule found; assume end of file
        sec_end = len(wp_text)
    else:
        sec_end = sec_end_rel  # exclude the terminator from replacement
    return sec_start, sec_end


