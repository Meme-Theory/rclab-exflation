def build_full_rule_file_text(current_text: str,
                              rule_block_text: str) -> str:
    """Splice the K=2 OPERATIONAL-ALIGNMENT calibration block into the
    rule file at cross-pillar-bridge-anatomy.md §"Deferred-pending
    intermediate verdict-class" immediately BEFORE the existing
    "**Audit**:" line.

    IDEMPOTENT: if the K=2 block (identified by RULE_FILE_BLOCK_HEADER_MARKER)
    is already present, REPLACE it rather than appending a second one.
    Replacement scope: from the header marker line through the next
    "**Audit**:" line boundary (exclusive). This makes the splice safe
    against multi-run / corrective-emission patterns under
    `gate-verdicts.md §"Option A — sig_5 remediation"`.

    The splice point is the first "**Audit**:" line that appears after
    the §"Deferred-pending intermediate verdict-class" section heading.
    """
    sec_idx = current_text.find(RULE_FILE_SECTION_HEADER)
    if sec_idx < 0:
        raise RuntimeError(
            f"§\"Deferred-pending intermediate verdict-class\" section "
            f"heading not found in rule file (marker="
            f"{RULE_FILE_SECTION_HEADER!r})"
        )

    # Idempotency check: is the K=2 block already present?
    existing_block_idx = current_text.find(
        RULE_FILE_BLOCK_HEADER_MARKER, sec_idx
    )
    if existing_block_idx >= 0:
        # Block exists — replace it. Find its bounds:
        #   start: the line containing RULE_FILE_BLOCK_HEADER_MARKER
        #          (walk back to the newline before it; the marker is
        #           wrapped in bold ** so the actual line starts at the
        #           preceding newline + 1)
        block_line_start = current_text.rfind(
            "\n", 0, existing_block_idx
        ) + 1
        # end: the next "**Audit**:" line after the existing block
        block_audit_idx = current_text.find(
            RULE_FILE_INSERT_BEFORE, existing_block_idx
        )
        if block_audit_idx < 0:
            raise RuntimeError(
                "Existing K=2 block found but no following **Audit**: "
                "line — file is structurally corrupt; aborting splice"
            )
        # Remove the existing block (from line_start through audit_idx
        # exclusive) and insert the new rule_block_text in its place
        new_text = (
            current_text[:block_line_start] +
            rule_block_text +
            current_text[block_audit_idx:]
        )                                                            # (local)
        return new_text

    # Block not yet present — insert before the first **Audit**: line
    audit_idx = current_text.find(RULE_FILE_INSERT_BEFORE, sec_idx)
    if audit_idx < 0:
        raise RuntimeError(
            f"\"**Audit**:\" line not found after section header "
            f"(marker={RULE_FILE_INSERT_BEFORE!r})"
        )

    # Insert rule_block_text BEFORE the **Audit**: line
    new_text = (
        current_text[:audit_idx] +
        rule_block_text +
        current_text[audit_idx:]
    )                                                                # (local)
    return new_text


def build_full_corpus_text(current_text: str,
                           corpus_bullet_text: str) -> str:
    """Splice the new sub-bullet (c) §VII.AV OPERATIONAL-ALIGNMENT into
    corpus §1 Instance #3 between the existing sub-bullets (a) + (b) and
    the closing prose "Both sub-class tags route to plan-freeze
    advisory...".

    IDEMPOTENT: if the (c) sub-bullet (identified by
    CORPUS_K2_OA_BULLET_MARKER) is already present in §1, REPLACE the
    existing sub-bullet text rather than append a second one. Replacement
    scope: from the start of the line containing the marker through the
    end of that bullet (which terminates at the next newline that is
    followed by either a non-space character or the closing prose
    line).

    Locator (insert path): the first occurrence of "Both sub-class tags
    route to plan-freeze advisory" inside corpus §1 — the new (c) bullet
    is inserted BEFORE that closing prose.

    The closing prose begins with the multi-line block:
        "  Both sub-class tags route to plan-freeze advisory (S2) severity..."
    indented with 2 spaces matching the parent-bullet level of Instance #3.
    The (c) sub-bullet uses the same 2-space indentation as (a) + (b).
    """
    # Find the §1 section heading first
    sec1_idx = current_text.find("## §1. Level-2 Layer Distinction")
    if sec1_idx < 0:
        raise RuntimeError("Corpus §1 heading not found")

    # Find the next section heading (§2) to bound the search
    sec2_idx = current_text.find("\n## §2.", sec1_idx)
    if sec2_idx < 0:
        sec2_idx = len(current_text)

    # Idempotency check: is the (c) sub-bullet already present?
    existing_bullet_idx = current_text.find(
        CORPUS_K2_OA_BULLET_MARKER, sec1_idx
    )
    if 0 <= existing_bullet_idx < sec2_idx:
        # Bullet exists in §1 — replace it. Find its bounds:
        #   start: walk back to the newline before its line
        bullet_line_start = current_text.rfind(
            "\n", 0, existing_bullet_idx
        ) + 1
        # end: walk forward to the next line that does NOT start with
        # whitespace (the bullet's continuation indented at 4+ spaces;
        # next non-indented line is the closing prose OR an audit row).
        # Simpler heuristic: the bullet is a single long line terminated
        # by "\n"; advance to the first newline after the marker.
        bullet_line_end = current_text.find(
            "\n", existing_bullet_idx
        )
        if bullet_line_end < 0:
            raise RuntimeError(
                "Existing (c) sub-bullet found but no terminating "
                "newline; file is structurally corrupt; aborting splice"
            )
        bullet_line_end += 1  # include the newline itself
        # Replace
        new_text = (
            current_text[:bullet_line_start] +
            corpus_bullet_text +
            current_text[bullet_line_end:]
        )                                                            # (local)
        return new_text

    sec1_block = current_text[sec1_idx:sec2_idx]                     # (local)

    # Find the closing "Both sub-class tags route" prose within §1
    closing_marker = "  Both sub-class tags route to plan-freeze advisory"
    close_rel = sec1_block.find(closing_marker)
    if close_rel < 0:
        # Try without leading spaces
        closing_marker = "Both sub-class tags route to plan-freeze advisory"
        close_rel = sec1_block.find(closing_marker)
        if close_rel < 0:
            raise RuntimeError(
                "Corpus §1 Instance #3 closing prose marker "
                "(\"Both sub-class tags route to plan-freeze advisory\") "
                "not found"
            )

    # Compute absolute insertion position; walk back to start of the line
    abs_close_pos = sec1_idx + close_rel                             # (local)
    # Find the newline immediately preceding the closing prose line
    nl_pos = current_text.rfind("\n", 0, abs_close_pos)
    if nl_pos < 0:
        raise RuntimeError("No newline before closing prose marker")

    # Insertion point is right after the newline (= start of closing line)
    insert_pos = nl_pos + 1                                          # (local)

    # Insert sub-bullet text right before the closing prose line
    # (so the sub-bullet appears at the same indent depth as (a)/(b)).
    new_text = (
        current_text[:insert_pos] +
        corpus_bullet_text +
        current_text[insert_pos:]
    )                                                                # (local)
    return new_text


