def scan_all_header_levels(registry_text: str) -> dict:
    """Scan ALL ### §VII.B[A-Z] and #### §VII.B[A-Z] header patterns
    on the registry text to determine slot occupancy + next-free
    letter.

    Per epistemic-discipline.md "Registry-Write Hygiene under
    Parallel-Writer Race" item 1: scan ALL header levels (### + ####)
    to avoid under-counting existing slots that would produce
    collision under parallel writers.

    Returns a dict with occupied slot letters + next-free letter +
    §VII.BE occupancy status.
    """
    # Match ### §VII.B[A-Z] at all header levels (3 or 4 hashes)
    pat = re.compile(r'^#{3,4}\s+§VII\.B([A-Z])\b', re.MULTILINE)  # (local)
    matches = pat.findall(registry_text)  # (local)
    occupied_letters = sorted(set(matches))  # (local)
    vii_be_occupied = 'E' in occupied_letters  # (local)

    # Determine next-free letter in B[A-Z] range
    used = set(occupied_letters)  # (local)
    next_free_letter = None  # (local)
    for c in "ABCDEFGHIJKLMNOPQRSTUVWXYZ":
        if c not in used:
            next_free_letter = c
            break

    return {
        "occupied_letters_in_VII_B_range": occupied_letters,
        "occupied_count": int(len(occupied_letters)),
        "vii_be_occupied": bool(vii_be_occupied),
        "next_free_letter_in_VII_B_range": next_free_letter,
        "vii_be_target_status": (
            "OCCUPIED-VERIFY-INTACT" if vii_be_occupied
            else "VACANT-WRITE-NEW"
        ),
    }


