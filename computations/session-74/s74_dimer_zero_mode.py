# Generators of the C^2 coset: the off-diagonal directions (e_1, e_2, f_1, f_2).
# Paper 13 eq (1.3): phi = [[0, -phi_dagger], [phi, 0]] embedded into 3x3.
def embed_C2(col_vec, real=True):
    """
    Embed a C^2 vector phi = (x + i y, z + i w) into su(3) via
    phi_matrix = [[0, -phi^dagger], [phi, 0]]
    where the first row/col is the u(1)/singlet direction and the 2x2 lower
    block is the u(2) stabilizer block.
    `col_vec` is length-2 complex.
    """
    M = np.zeros((3, 3), dtype=complex)                             # (local)
    M[1, 0] = col_vec[0]
    M[2, 0] = col_vec[1]
    M[0, 1] = -np.conj(col_vec[0])
    M[0, 2] = -np.conj(col_vec[1])
    return M

