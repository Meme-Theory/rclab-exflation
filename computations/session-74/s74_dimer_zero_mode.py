# =====================================================================
#  SECTION 2: Commutator-based commutation test
# =====================================================================

# An element h in SU(3) "commutes with" the Lie-algebra generator X in the
# Ad-action sense if Ad_h X = X, i.e. h X h^{-1} = X, i.e. [h, X] = 0.
# For the diagonal h = diag(e^{i a}, e^{i b}, e^{i c}) this is a simple
# eigenvalue computation on the matrix elements of X.

def commutator(A, B):
    return A @ B - B @ A

def commutes_with(h, generators, tol=1e-12):
    """Return True if h commutes with every generator in `generators`."""
    for X in generators:
        if np.max(np.abs(commutator(h, X))) > tol:
            return False
    return True

def commutation_deviation(h, generators):
    """Return the max element-wise |[h, X]| over all X in `generators`."""
    dev = 0.0                                                       # (local)
    for X in generators:
        dev = max(dev, float(np.max(np.abs(commutator(h, X)))))
    return dev

