    valid = cond_A and cond_B                                       # (local)
    is_center = (N == 1) or (N == 3) or acts_trivially_on_phi       # (local) center-like

    return {
        "N": N,
        "theta": 2 * PI / N,
        "g_diag": np.diag(g).copy(),
        "dev_u2": dev_u2,
        "dev_C2": dev_C2,
        "cond_A_commutes_u2": cond_A,
        "cond_B_not_commute_C2": cond_B,
        "valid_selection_rule": valid,
        "phi_weight_multiplier": action_on_phi,
        "acts_trivially_on_C2": acts_trivially_on_phi,
        "is_center_like": is_center,
    }

