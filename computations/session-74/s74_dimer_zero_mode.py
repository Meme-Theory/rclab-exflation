I_u = 1j   # (local)

gamma_0 = np.diag([-2*I_u, I_u, I_u])                             # (local) u(1) generator

sigma_x = np.array([[0, 1], [1, 0]], dtype=complex)               # (local)
sigma_y = np.array([[0, -1j], [1j, 0]], dtype=complex)            # (local)
sigma_z = np.array([[1, 0], [0, -1]], dtype=complex)              # (local)

def embed_su2(P):
    """Embed a 2x2 traceless-Hermitian matrix into the lower-right block of su(3)."""
    M = np.zeros((3, 3), dtype=complex)                            # (local)
    M[1:, 1:] = 1j * P
    return M

su2_T1 = embed_su2(sigma_x)                                        # (local)
su2_T2 = embed_su2(sigma_y)                                        # (local)
su2_T3 = embed_su2(sigma_z)                                        # (local)

