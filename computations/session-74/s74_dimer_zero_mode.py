def T_C1_element(theta):
    """
    Centralizer of u(2) inside SU(3): T_{C1} = { diag(e^{-2 i theta}, e^{i theta}, e^{i theta}) }.
    This is the 1-parameter subgroup generated by the Killing field
    gamma_0 = diag(-2i, i, i) from Baptista paper 13 eq (2.32) at phi=0.
    """
    return np.diag([
        np.exp(-2j * theta),
        np.exp(1j * theta),
        np.exp(1j * theta),
    ])

def Z_N_generator(N):
    """Return the generator of Z_N as a diagonal T_{C1} element with theta = 2 pi / N."""
    theta = 2 * PI / N                                              # (local)
    return T_C1_element(theta)

