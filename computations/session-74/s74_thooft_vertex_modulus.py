# --------------------------------------------------------------------------------------
# Step 2 — g^{-2}(tau) from Jensen-deformation rule
# --------------------------------------------------------------------------------------

def g_inv_sq_of_tau(tau: np.ndarray) -> np.ndarray:
    """
    Inverse-squared gauge coupling of the Jensen-deformed SU(3) gauge sector.

        g^{-2}(tau) = g^{-2}(0) * exp(-2 tau),  with g^{-2}(0) = 1 (normalized)

    This is the framework's canonical Jensen deformation rule for the ratio
    g_1/g_2(M_Z) = exp(-2 tau) applied to the SU(3) sector; with g^{-2}(0) = 1
    it sets g^2(0) = 1 (the round-SU(3) reference) and g^2(tau) = exp(+2 tau)
    grows monotonically with tau.
    """
    tau = np.asarray(tau, dtype=float)
    return np.exp(-2.0 * tau)


def g_sq_of_tau(tau: np.ndarray) -> np.ndarray:
    """Jensen-deformed g^2(tau) = 1 / g^{-2}(tau) = exp(+2 tau)."""
    return 1.0 / g_inv_sq_of_tau(tau)


def S_inst_of_tau(tau: np.ndarray) -> np.ndarray:
    """BPST instanton action S_inst = 8 pi^2 / g^2(tau) = 8 pi^2 * exp(-2 tau)."""
    return (8.0 * PI**2) * g_inv_sq_of_tau(tau)


# --------------------------------------------------------------------------------------
# Step 3 — 't Hooft vertex magnitude V_{tHooft}(tau)
# --------------------------------------------------------------------------------------

def V_thooft_of_tau(tau: np.ndarray, Lambda: float) -> np.ndarray:
    """
    't Hooft vertex contribution to the effective modulus potential:

        V_tHooft(tau) = K * exp(-S_inst(tau)) * Lambda^4
                     = K * exp(-8 pi^2 * exp(-2 tau)) * Lambda^4

    Units: M_KK^4 when Lambda is in M_KK units.
    """
    return K_tHooft * np.exp(-S_inst_of_tau(tau)) * Lambda**4


# --------------------------------------------------------------------------------------
# Step 4 — Analytic + finite-difference derivatives
# --------------------------------------------------------------------------------------

def dV_thooft_dtau_analytic(tau: np.ndarray, Lambda: float) -> np.ndarray:
    """
    Analytic derivative:

        dV_tHooft/dtau = K * Lambda^4 * d/dtau [exp(-8 pi^2 exp(-2 tau))]
                      = K * Lambda^4 * exp(-8 pi^2 exp(-2 tau)) * (16 pi^2 exp(-2 tau))

    Always positive (vertex is monotonically increasing in tau).
    """
    pref = 16.0 * PI**2 * np.exp(-2.0 * np.asarray(tau, dtype=float))
    return V_thooft_of_tau(tau, Lambda) * pref


def dV_thooft_dtau_finite_difference(tau: np.ndarray, Lambda: float,
                                     h: float = 1e-5) -> np.ndarray:
    """Central finite-difference check for dV/dtau (cross-check of the analytic result)."""
    tau = np.asarray(tau, dtype=float)
    return (V_thooft_of_tau(tau + h, Lambda) - V_thooft_of_tau(tau - h, Lambda)) / (2.0 * h)


# --------------------------------------------------------------------------------------
# Step 5 — Gate classification
# --------------------------------------------------------------------------------------

def classify_gate(dV_tau048: float) -> tuple[str, str]:
    """Return (verdict, reason) for TH-OOFT-VERTEX-MODULUS-74."""
    ratio = abs(dV_tau048) / DS_BARE
    if ratio >= GATE_PASS_FRACTION:
        return "PASS", (f"|dV_tHooft/dtau|(tau=0.48) = {abs(dV_tau048):.3e} M_KK^4 "
                        f">= {GATE_PASS_THRESHOLD:.3e} = 10% of bare")
    if ratio >= GATE_INFO_FRACTION:
        return "INFO", (f"|dV_tHooft/dtau|(tau=0.48) = {abs(dV_tau048):.3e} M_KK^4 "
                        f"in [{GATE_INFO_THRESHOLD:.3e}, {GATE_PASS_THRESHOLD:.3e}] "
                        f"(1%-10% of bare)")
    return "FAIL", (f"|dV_tHooft/dtau|(tau=0.48) = {abs(dV_tau048):.3e} M_KK^4 "
                    f"< {GATE_INFO_THRESHOLD:.3e} (< 1% of bare); vertex is negligible")


