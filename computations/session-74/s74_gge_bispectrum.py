# (exp(-r) ~ exp(-3.57) for B1), the f_NL value is defined relative to
# the POWER SPECTRUM which is also squeezed.  The RATIO B/P^2 is what
# appears in f_NL, and this ratio has a residual exp(-r/2) scaling.
#
# HOWEVER, the standard Senatore-Zaldarriaga result assumes the vacuum
# is Bunch-Davies at horizon crossing.  In exflation, the vacuum IS
# the squeezed state (it's what emerges from the fold).  The definition
