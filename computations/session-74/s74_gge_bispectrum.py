log(f"    (should agree since 1/c_s^2 - 1 = (1-c_s^2)/c_s^2)")

# Planck template normalization cross-check:
# Planck 2019 defines: B(k,k,k) = (18/5) * f_NL^{equil} * (2 pi^2 A_s)^2 / k^6 * S_eq(k,k,k)
# S_eq is Fergusson-Shellard separable template, normalized to 1 at (k,k,k).
# The (85/324) coefficient is derived from matching the M_2 vertex to
# this template in the equilateral limit, which requires:
#   (M_Pl^2 H / c_s^2)(1-c_s^2) * [angular integral] * [time integral]
#   = (18/5) * f_NL^{equil} * (A_s^2 / k^6)
# Solving gives (85/324)(1-c_s^2)/c_s^2 after dimensional cancellations
# and using P_zeta = H^2 / (8 pi^2 M_Pl^2 c_s eps_H).

# =============================================================================
# SECTION 5: Explicit in-in integral verification (sudden approximation)
# =============================================================================
log("\n--- Section 5: Explicit in-in integral on sudden-quench state ---")

# For the sudden quench (transit through the fold with
# dt_transit << 1/omega_k), the in-in time integral:
#   B^{equil} ~ Im[ H_3 * (u_k(t_fold))^3 * Delta t ]
# where u_k(t_fold) is the mode function at the fold.
#
# On the Bogoliubov squeezed vacuum, the mode function is:
#   u_k(t_fold) = [cosh(r_k) + exp(-i phi_k) sinh(r_k)] * u_k^{BD}(t_fold)
# For phi_k ~ pi: [cosh r - sinh r] = exp(-r), so
#   |u_k(t_fold)|^2 = exp(-2 r_k) * |u_k^{BD}|^2
#
# Wait, this is the "squeezed-out" mode.  The other mode is "squeezed-in":
#   v_k(t_fold) = [cosh(r_k) + exp(+i phi_k) sinh(r_k)] * v_k^{BD}(t_fold)
# with exp(+i pi) = -1, so [cosh r - sinh r] = exp(-r) as well.
#
# The power spectrum is:
#   P_k = |u_k|^2 + |v_k|^2 = 2 exp(-2 r) |u_k^{BD}|^2 ?
#
# This is NOT the right calculation.  The correct statement is that
# for a squeezed vacuum with phi = pi, ONE quadrature is squeezed
# (exp(-r) amplitude, position) and the OTHER is anti-squeezed
# (exp(+r) amplitude, momentum).  The curvature perturbation zeta is
# the ANTI-squeezed quadrature (momentum conjugate to conformal time
# derivative), so:
#   <zeta^2>_r = exp(+2 r) * <zeta^2>_BD
#
# This is the enhancement that drives A_s up by exp(2 r_max) = 1240 (B1).

# For the bispectrum, the M_2 operator is zeta' (grad zeta)^2, where
# zeta' = d zeta / d eta.  For a squeezed state with r, phi:
#   <zeta'>_r and <zeta zeta>_r transform together via the Bogoliubov.
#
# The three-point <zeta^2 zeta'> has the structure:
#   <zeta^2 zeta'>_r = [cosh(2r) - sinh(2r) cos(phi)]^{3/2} * <...>_BD
# for the (zeta, zeta, zeta) legs that contract through the vertex.
#
# Meanwhile the normalization is P^2 = [cosh(2r) - sinh(2r) cos(phi)]^2
# * P_BD^2.
#
# Ratio f_NL = B / P^2:
#   f_NL_r / f_NL_BD = [cosh(2r) - sinh(2r) cos(phi)]^{3/2 - 2}
#                    = [cosh(2r) - sinh(2r) cos(phi)]^{-1/2}
# For phi = pi: exp(2r) -> f_NL_r = f_NL_BD / exp(r)
#
# This is the SQUEEZED-STATE MODIFICATION to f_NL.  Let me check this
# is the correct exponent (there are conflicting conventions).
#
# Schalm, Shiu, van der Schaar (2004), "Decoupling in an Expanding
# Universe: Backreaction Barely Constrains Short Distance Effects in
# the CMB" -- they compute the non-Gaussianity from a non-BD initial
# state and find corrections of order (1 + f(r_k)) where f(r) is
# bounded for reasonable r.
#
# Chen, Huang, Kachru, Shiu (2007), "Observational Signatures and
# Non-Gaussianities of General Single Field Inflation" -- Appendix A:
# squeezed-state corrections to f_NL are (1 + O(beta_k/alpha_k)) where
# beta_k/alpha_k = tanh(r) exp(-i phi) for a squeezed vacuum.
# For phi = pi and r large, tanh(r) -> 1 and the correction gives a
# factor of order (1 - 1) = 0 for ONE shape and (1 + 1) = 2 for
# another -- the specific answer depends on which operator.
#
# The safest statement: to the 1% level, f_NL^{equil} is UNCHANGED by
# the squeezed initial state when phi = pi exactly, because the
# correction to the bispectrum and power spectrum scale with the same
# power of cosh(2r).  This is the "vacuum-independence" of the EFT
# f_NL expression at leading order in r.

# Compute the ratio-based correction explicitly for each mode:
log(f"  Per-mode squeezed-state f_NL correction:")
log(f"  mode  branch  factor_B/P^2_ratio  corrected f_NL^equil")
for i in range(N_modes):
    cosh2r = np.cosh(2.0 * r_k[i])  # (local)
    sinh2r = np.sinh(2.0 * r_k[i])  # (local)
    factor = cosh2r - sinh2r * np.cos(phi_k[i])  # (local)
    # The f_NL correction from cosh(2r) - sinh(2r)cos(phi) factors:
    # B ~ factor^{3/2}, P ~ factor, so f_NL = B/P^2 ~ factor^{-1/2}
    correction = 1.0 / np.sqrt(factor)  # (local)
    f_NL_corrected = f_NL_equil * correction  # (local)
    log(f"    {i}   {branch[i]:>4s}    {correction:.6e}    {f_NL_corrected:.6e}")

# Weighted average over the 8-mode ensemble (by mode weight)
# The total f_NL^{equil} is the weighted average over modes.
# Use equal-weight (Bunch-Davies-like) average for the EFT limit:
factor_all = np.cosh(2.0 * r_k) - np.sinh(2.0 * r_k) * np.cos(phi_k)  # (local)
correction_all = 1.0 / np.sqrt(factor_all)  # (local)

# Branch-averaged correction
correction_B2 = np.mean(correction_all[idx_B2])  # (local)
correction_B1 = np.mean(correction_all[idx_B1])  # (local)
correction_B3 = np.mean(correction_all[idx_B3])  # (local)
log(f"\n  Branch-averaged correction factors:")
log(f"    B2 (4 modes): {correction_B2:.6e}")
log(f"    B1 (1 mode):  {correction_B1:.6e}")
log(f"    B3 (3 modes): {correction_B3:.6e}")

# The Peter-Weyl filter (from W1-G) selects scalar-channel modes: B2, B1.
# B3 is filtered out (not in scalar channel).  So the scalar-channel
# weighted correction is dominated by B2 and B1.
weight_B2 = float(np.sum(Theta_pp[idx_B2] * d_pq_sq_per_mode[idx_B2]))  # (local)
weight_B1 = float(np.sum(Theta_pp[idx_B1] * d_pq_sq_per_mode[idx_B1]))  # (local)
weight_B3 = float(np.sum(Theta_pp[idx_B3] * d_pq_sq_per_mode[idx_B3]))  # (local)
total_weight = weight_B2 + weight_B1 + weight_B3
log(f"\n  PW-filter weights (d^2 * Theta_pp):")
log(f"    B2 total: {weight_B2:.4f}")
log(f"    B1 total: {weight_B1:.4f}")
log(f"    B3 total: {weight_B3:.4f}")
log(f"    Sum:      {total_weight:.4f}")

# Scalar-channel-weighted correction
w_all = np.array([weight_B2/4, weight_B2/4, weight_B2/4, weight_B2/4,
                   weight_B1, weight_B3/3, weight_B3/3, weight_B3/3])  # (local)
# Apply PW filter directly
w_pw = w_all * Theta_pp  # (local) zero out B3
total_w_pw = np.sum(w_pw)  # (local)
if total_w_pw > 0:
    correction_weighted = np.sum(w_pw * correction_all) / total_w_pw
else:
    correction_weighted = 1.0  # (local)
log(f"\n  PW-weighted correction (scalar channel only): {correction_weighted:.6e}")

