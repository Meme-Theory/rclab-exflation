# For each eigenvector, determine:
# 1. Which C_2(U(2)) eigenvalue it has
# 2. Which C_2(SU(2)) eigenvalue (-> spin j)
# 3. Which T_7^2 eigenvalue (-> U(1) charge)
# 4. Which Hessian cluster it belongs to

# Identify irrep label from (C_2(SU(2)), T_7^2)
# NOTE: Our generators are ANTI-HERMITIAN, so C_2 eigenvalues are NEGATIVE.
# Standard SU(2): C_2 = -j(j+1) in our convention.
# T_7^2 = -Y^2 where Y is the U(1) eigenvalue.
def identify_irrep(c2_su2, t7_sq, tol=0.15):
    """Identify SU(2) x U(1) irrep from Casimir values.
    Convention: generators are anti-Hermitian, so C_2(SU(2)) = -j(j+1), T_7^2 = -Y^2.
    """
    # SU(2) spin from |C_2(SU(2))| = j(j+1)
    c2_pos = abs(c2_su2)  # Make positive
    disc = 1 + 4*c2_pos
    j = (-1 + sqrt(disc)) / 2
    j_round = round(2*j) / 2  # Round to nearest half-integer

    # U(1) charge from |T_7^2| = Y^2
    Y_sq = abs(t7_sq)

    # Label the SU(2) spin
    j_labels = {0.0: "0", 0.5: "1/2", 1.0: "1", 1.5: "3/2", 2.0: "2", 2.5: "5/2", 3.0: "3"}
    j_label = j_labels.get(j_round, f"{j_round:.2f}")

    # Label the U(1) charge. Y^2 values: 0, 3/4, 3
    # Y=0: Y^2=0; Y=sqrt(3)/2: Y^2=3/4; Y=sqrt(3): Y^2=3
    if Y_sq < 0.01:
        y_label = "0"
    elif abs(Y_sq - 0.75) < 0.1:
        y_label = "q"  # sqrt(3)/2
    elif abs(Y_sq - 3.0) < 0.1:
        y_label = "2q"  # sqrt(3)
    else:
        y_label = f"Y^2={Y_sq:.4f}"

    # Identify the Sym^2 origin
    if j_round == 0 and Y_sq < 0.01:
        origin = "singlet(k/y/m)"
    elif j_round == 0.5 and abs(Y_sq - 0.75) < 0.1:
        origin = "k*m or y*m"
    elif j_round == 1.0 and Y_sq < 0.01:
        origin = "k*y or S2(m)"
    elif j_round == 1.0 and abs(Y_sq - 3.0) < 0.1:
        origin = "S2(m)"
    elif j_round == 1.5 and abs(Y_sq - 0.75) < 0.1:
        origin = "k*m"
    elif j_round == 2.0 and Y_sq < 0.01:
        origin = "S2(k)"
    else:
        origin = "?"

    return f"j={j_label}, Y={y_label} [{origin}]"

