# The Ad action on the metric space: for generator e_alpha with structure constants f,
#   (T_alpha . h)_{ab} = sum_c [ f_{alpha,a,c} h_{cb} + f_{alpha,b,c} h_{ac} ]
#
# In the Sym^2 basis {B_k}, the 36x36 matrix is:
#   (T_alpha)_{kl} = <B_k, T_alpha . B_l>
#
# where T_alpha . B_l is computed as the 8x8 matrix:
#   (T_alpha . B_l)_{ab} = sum_c f_{alpha,a,c} (B_l)_{cb} + sum_c f_{alpha,b,c} (B_l)_{ac}

def ad_action_on_matrix(alpha, M, f_abc):
    """Compute the infinitesimal Ad(e_alpha) action on a symmetric 8x8 matrix M.
    (T_alpha . M)_{ab} = sum_c f_{alpha,a,c} M_{cb} + sum_c f_{alpha,b,c} M_{ac}
    """
    n = M.shape[0]
    result = np.zeros((n, n), dtype=np.float64)
    for a in range(n):
        for b in range(n):
            val = 0.0  # (local)
            for c in range(n):
                val += f_abc[alpha, a, c] * M[c, b]
                val += f_abc[alpha, b, c] * M[a, c]
            result[a, b] = val
    return result

def build_generator_36(alpha, basis, f_abc):
    """Build the 36x36 matrix of T_alpha acting on Sym^2(R^8)."""
