def compute_structure_constants(gens):
    """f_{abc} from [e_a, e_b] = f_{abc} e_c.
    Uses the trace formula: f_{abc} = -2 Tr([e_a, e_b] e_c)
    for our normalization Tr(e_a e_b) = -1/2 delta_{ab}."""
    n = len(gens)
    f = np.zeros((n, n, n), dtype=np.float64)
    for a in range(n):
        for b in range(a+1, n):
            comm = gens[a] @ gens[b] - gens[b] @ gens[a]
            for c in range(n):
                val = -2.0 * np.trace(comm @ gens[c])  # (local)
                f[a,b,c] = val.real
                f[b,a,c] = -val.real
    return f

