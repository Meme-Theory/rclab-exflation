def compute_rho_fit(nz: np.ndarray) -> dict:
    """Polynomial fit rho(s) = Sum_{k=0..4} rho_k * (s-3)^k on s in [2.5, 3.5].

    The Mellin-Barnes lower-half asymptotic order is capped at deg=4
    (regulator-pin tag (s-3)^k for k=0..4 per plan line 402); higher-order
    contributions are suppressed by the asymptotic L_max -> infinity
    Mellin-Barnes lower-half decomposition; finite-L corrections add
    measurable higher-order Taylor coefficients (this is the substrate's
    finite-discrete signature).

    SUBSTITUTION-CHAIN NOTE
    -----------------------
    At finite L_max=10 the spectrum is finite-discrete, so V(s) =
    Sum_i |lambda_i|^{-2s} is an ENTIRE function of s (no pole at any
    finite s, including s=3). The "substrate-distance-1 pole at s=3"
    is the L_max -> infinity ASYMPTOTIC analytic continuation feature
    (Connes-Moscovici 1995 finite-spectral-triple residue formula
    extracts the residue as a regulated trace from the finite-L data).
    Diagnostic verification: V(3.0) = 4.104e+02 (finite); R(s) :=
    (s-3)*V(s) gives R(3) = 0 exactly by construction, NOT by simple-
    pole subtraction.

    Therefore the rho-fit IS on V(s) directly (NOT on (s-3)*V(s));
    the rho_k coefficients are the Taylor expansion of V(s) at s=3.
    The Mellin-Barnes lower-half asymptotic order pre-registered as
    deg <= 4 captures the leading L -> infinity terms; finite-L
    corrections add a small higher-order tail that the deg-4 cap
    intentionally neglects (per pre-registration).
    """
    s_grid = np.linspace(RHO_S_MIN, RHO_S_MAX, N_RHO_PTS)
    # V(s) is analytic at s=3 at finite L_max; no need to excise s=3 from fit.
    s_fit = s_grid
    V = np.array([V_of_s(nz, float(s)) for s in s_fit])

    # Polynomial fit in u = (s - 3), degree <= RHO_FIT_DEG_CAP, of V(s) directly.
    u = s_fit - 3.0
    coeffs = np.polyfit(u, V, RHO_FIT_DEG_CAP)                  # (local) returns highest first
    V_fit = np.polyval(coeffs, u)                               # (local)
    resid = V - V_fit                                           # (local)
    # Normalised residual: RMS(resid) / mean(|V|).
    rms = float(np.sqrt(np.mean(resid ** 2)))                   # (local)
    R_scale = float(np.mean(np.abs(V)))                         # (local) mean |V|
    rho_fit_residual = rms / R_scale if R_scale > 0 else float("inf")
    # Keep the "R_vals" and "R_fit" output keys for plot+JSON back-compatibility:
    # at finite L_max the regular part IS V(s) itself.
    R_vals = V
    R_fit = V_fit

    # Polynomial degree (#non-trivial coefficients) — declared <= 4 by
    # construction; we evaluate the actual significant degree by checking
    # which coefficients are above 1% of the largest in magnitude.
    abs_c = np.abs(coeffs)
    significant = abs_c > 0.01 * abs_c.max()
    # Effective degree: highest non-trivially-zero index from the highest end.
    effective_deg = int(RHO_FIT_DEG_CAP - np.argmax(significant)) if significant.any() else 0

    rho_k = list(reversed([float(c) for c in coeffs]))          # (local) k=0..4 order
    return {
        "s_grid": s_grid,
        "s_fit": s_fit,
        "V_fit_input": V,
        "R_vals": R_vals,
        "R_fit": R_fit,
        "rho_k": rho_k,
        "polynomial_deg": int(RHO_FIT_DEG_CAP),
        "effective_polynomial_deg": effective_deg,
        "rho_fit_residual": float(rho_fit_residual),
        "rms_abs_resid": rms,
        "R_scale": R_scale,
        "n_pts_fit": int(s_fit.size),
        "n_pts_intended": int(N_RHO_PTS),
    }


