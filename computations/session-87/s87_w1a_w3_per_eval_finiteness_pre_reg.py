    s_right = np.linspace(3.0 + ds_apex, 3.0 + APEX_EPS, N_APEX_PTS // 2)
    s_apex = np.concatenate([s_left, s_right])
    V = np.array([V_of_s(nz, float(s)) for s in s_apex])

    # Direct apex max.
    apex_value = float(np.max(np.abs(V)))                       # (local)
    # Plan-line-432 algebraic floor for cross-check (upper bound).
