# =============================================================================
#  Section 2: SU(1,1) Bargmann representation
# =============================================================================
#
# The Bargmann (fundamental) representation of SU(1,1) for a two-mode squeeze:
#
#   S(r, phi) = [[cosh(r),           e^{i*phi} * sinh(r)],
#                [e^{-i*phi} * sinh(r), cosh(r)          ]]
#
# This satisfies det(S) = cosh^2(r) - sinh^2(r) = 1, as required for SU(1,1).
#
# Group multiplication: S_compound = S_1 * S_2 gives a new SU(1,1) element
# from which we extract compound (r, phi).
#
# The generators are:
#   K_0 = 0.5 * [[1, 0], [0, -1]]     (number operator)
#   K_+ = 0.5 * [[0, 1], [0, 0]]      (squeeze creation)
#   K_- = 0.5 * [[0, 0], [1, 0]]      (squeeze annihilation)
#
# The BCS squeeze is parametrized by (r_k, phi_k) for each mode k.
# The spatial phase fluctuation adds a random phase phi drawn from von Mises.
# The spatial element is S(r_spatial, phi_spatial) where r_spatial encodes
# the amplitude of inter-site coherence and phi_spatial is the random angle.

def su11_matrix(r, phi):
    """Construct the SU(1,1) Bargmann matrix S(r, phi)."""
    cr = np.cosh(r)
    sr = np.sinh(r)
    ep = np.exp(1j * phi)
    em = np.exp(-1j * phi)
    return np.array([[cr, ep * sr],
                     [em * sr, cr]], dtype=complex)


def extract_su11_params(S):
    """
    Extract (r, phi) from an SU(1,1) Bargmann matrix.

    Given S = [[alpha, beta], [beta*, alpha*]] with |alpha|^2 - |beta|^2 = 1:
        cosh(r) = |alpha|
        sinh(r) = |beta|
        phi = arg(beta) + arg(alpha)  -- but alpha is real if we started clean

    More precisely:
        r = arccosh(|S[0,0]|)
        phi = angle(S[0,1])
    """
    alpha = S[0, 0]
    beta = S[0, 1]
    r_out = np.arccosh(np.abs(alpha))
    phi_out = np.angle(beta)
    return float(r_out), float(phi_out)


def von_mises_pdf(phi, kappa):
    """Von Mises probability density function on [0, 2*pi)."""
    return np.exp(kappa * np.cos(phi)) / (2 * np.pi * float(bessel_I0(kappa)))


