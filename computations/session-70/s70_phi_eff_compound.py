# CRITICAL: The von Mises-averaged SU(1,1) matrix has det != 1.
# This means the averaged matrix is NOT in SU(1,1) -- it's a general positive
# map. The departure from det = 1 measures thermal decoherence.
#
# The physical compound squeeze must be renormalized back onto SU(1,1).
# Two canonical methods:
#
#   (A) Polar decomposition: project the averaged matrix onto SU(1,1) by
#       rescaling alpha -> alpha/sqrt(det), beta -> beta/sqrt(det)
#       This preserves the phase but reduces the squeeze.
#
#   (B) Trace-preserving map: the physical squeeze parameter is the one
#       that gives the same expectation values for SU(1,1) generators
#       as the averaged density matrix. This gives:
#       cosh(2*r_eff) = (|alpha|^2 + |beta|^2) / det

print(f"\n--- Section 7b: Decoherence-Corrected Compound ---")

r_compound_corrected = np.zeros(n_modes)
phi_compound_corrected = np.zeros(n_modes)
cosh2r_compound_corrected = np.zeros(n_modes)

for i in range(n_modes):
    a = alpha_compound[i]
    b = beta_compound[i]
    det_i = np.abs(a)**2 - np.abs(b)**2

    # Method A: Polar decomposition (project back to SU(1,1))
    sqrt_det = np.sqrt(det_i)
    a_norm = a / sqrt_det
    b_norm = b / sqrt_det
    # Now |a_norm|^2 - |b_norm|^2 = 1

    r_corrected = np.arccosh(np.abs(a_norm)) if np.abs(a_norm) >= 1.0 else 0.0
    phi_corrected = np.angle(b_norm)
    cosh2r_corrected = np.cosh(2 * r_corrected)

    r_compound_corrected[i] = r_corrected
    phi_compound_corrected[i] = phi_corrected
    cosh2r_compound_corrected[i] = cosh2r_corrected

