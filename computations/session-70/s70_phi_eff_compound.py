# =============================================================================
#  Section 5: Numerical SU(1,1) group multiplication + von Mises average
# =============================================================================
#
# For each mode k:
#   <S_compound>_k = integral_0^{2*pi} S(r_spatial, phi) * S(r_k, phi_k)
#                     * P_vM(phi; kappa) dphi
#
# This integral can be computed analytically for the matrix elements.
# The (0,0) element of the product:
#   [S1 * S2]_{00} = cosh(r1)*cosh(r2) + e^{i(phi1 - phi2)}*sinh(r1)*sinh(r2)
# The (0,1) element:
#   [S1 * S2]_{01} = cosh(r1)*e^{i*phi2}*sinh(r2) + e^{i*phi1}*sinh(r1)*cosh(r2)
#
# Averaging over phi1 (the spatial phase) with von Mises P_vM(phi1; kappa):
#   <e^{i*phi1}> = I_1(kappa) / I_0(kappa) = <cos(phi)>_spatial (for real part)
#   <e^{-i*phi1}> = I_1(kappa) / I_0(kappa)  (von Mises is symmetric)
#   <e^{i*(phi1 - phi2)}> = e^{-i*phi2} * I_1(kappa) / I_0(kappa)
#
# So:
#   <[S1*S2]_{00}> = cosh(r1)*cosh(r2) + e^{-i*phi2}*sinh(r1)*sinh(r2) * C
#   <[S1*S2]_{01}> = cosh(r1)*e^{i*phi2}*sinh(r2) + sinh(r1)*cosh(r2) * C * e^{+i*mean}
#
# where C = I_1(kappa)/I_0(kappa) = <cos(phi)> and mean=0 for centered von Mises.
#
# BUT: The von Mises is centered at phi=0 (the equilibrium Josephson phase).
# So <e^{i*phi}> = I_1(kappa)/I_0(kappa) is real and positive.

