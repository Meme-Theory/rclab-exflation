#
#   <alpha_compound> = cosh(r_s)*cosh(r_k) + C_vM * sinh(r_s)*sinh(r_k) * e^{-i*phi_k}
#   <beta_compound>  = cosh(r_s)*sinh(r_k)*e^{i*phi_k} + C_vM * sinh(r_s)*cosh(r_k)
