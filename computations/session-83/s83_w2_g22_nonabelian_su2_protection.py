# Section 8 -- Restriction / pullback: T^2_{SU(3)} -> T^1_{SU(2)}
# ---------------------------------------------------------------------------
#
# The key structural claim: the SU(2) Cartan sits inside the SU(3) Cartan as
# a 1D sub-torus. On the level of algebras,
#     C^\infty(T^2_{SU(3)}) \to C^\infty(T^1_{SU(2)})
# is surjective (restriction), and the pullback on cyclic cohomology
#     i^*: HC^n(T^2) -> HC^n(T^1)
# sends the T^2 volume form [dx_1 \wedge dx_2] (generator of H^2_dR(T^2)) to
# (dx_1 restricted to T^1) \wedge 0 = 0 because dx_2 pulls back to 0 on T^1.

def verify_pullback_volume_form_vanishes():
    """Verify: pullback of T^2 volume 2-form to T^1 sub-torus is zero.

    Consider T^2 with coordinates (theta_1, theta_2), T^1 \subset T^2 embedded
    as theta_2 = 0. Volume form on T^2: omega = d(theta_1) wedge d(theta_2).
    Pullback i^*omega on T^1: i^*(d theta_2) = d(theta_2 \circ i) = d(0) = 0.
    So i^* omega = d(theta_1) \wedge 0 = 0.
    """
    # Numeric verification: sample the pullback on a grid.
    # We encode theta_1 -> (theta_1, 0) and compute the Jacobian.
    N = 64                                          # (local) sample points
    thetas = np.linspace(0.0, 2.0 * PI, N)          # (local)
    # Parametrize T^1 in T^2 via (theta_1, theta_2) = (t, 0).
    # Tangent of T^1: (d/dt)(t, 0) = (1, 0).
    # Volume 2-form evaluates on (v_1, v_2) = vol(v_1, v_2) = v_1^x * v_2^y
    # - v_1^y * v_2^x. With only one tangent v_1, the 2-form vanishes.
    # (a 2-form needs 2 independent vectors; T^1 has only 1 tangent direction)
    max_pullback_value = 0.0                        # (local)
    for _ in thetas:
        # One tangent vector in R^2 at each point along the embedded T^1:
        # v = (1, 0).  Volume 2-form vol(v, v) = v_x * v_y - v_y * v_x = 0.
        v = np.array([1.0, 0.0])                    # (local)
        # 2-form: vol(u, w) = u_x * w_y - u_y * w_x
        vol_value = v[0] * v[1] - v[1] * v[0]       # (local) trivially 0
        max_pullback_value = max(max_pullback_value, abs(vol_value))
    return max_pullback_value < EPS_ZERO


def pullback_cohomology_T2_to_T1(n):
    """Pullback map on cohomology: HC^n(T^2) -> HC^n(T^1).

    Structural theorem: if the embedding is generic (not a 2-fold cover of T^2
    by T^1, which is impossible anyway since T^1 has no 2-forms), the pullback
    map on degree-n PRIMARY cohomology is:
       - deg 0: identity on constants -> rank 1
       - deg 1: H^1_dR(T^2) = C^2 with basis {d theta_1, d theta_2};
                i^*(d theta_1) = d theta_1, i^*(d theta_2) = 0.
                -> rank 1 (kernel = <d theta_2>)
       - deg 2: H^2_dR(T^2) = C (volume form); i^*(vol) = 0.
                -> rank 0. PRIMARY KILLED.
    """
    if n == 0:
        return 1  # constants pull back to constants
    if n == 1:
        return 1  # only theta_1 direction survives
    if n == 2:
        return 0  # volume form dies on 1D submanifold
    return 0


