def h_dR_T_r(r, n):
    """de Rham cohomology of the r-torus T^r = (S^1)^r in degree n.

    Kunneth: H^n_dR(T^r) has dimension binomial(r, n).
    For r = 1: H^0 = 1, H^1 = 1, H^{>=2} = 0.
    For r = 2: H^0 = 1, H^1 = 2, H^2 = 1, H^{>=3} = 0.
    For r = 3: H^0 = 1, H^1 = 3, H^2 = 3, H^3 = 1, H^{>=4} = 0.
    """
    if n < 0 or n > r:
        return 0
    from math import comb
    return comb(r, n)


def h_dR_S1(n):
    """de Rham cohomology of S^1 = T^1. Convenience wrapper."""
    return h_dR_T_r(1, n)


# ---------------------------------------------------------------------------
# Section 6 -- Cyclic cohomology on Cartan subalgebras C^\infty(T^r)
# ---------------------------------------------------------------------------
#
# By Connes' SBI long exact sequence for smooth commutative algebras:
#    HC^n(C^\infty(M)) = ker(d: Omega^n -> Omega^{n+1})
#                       (+) H^{n-2}_dR(M) (+) H^{n-4}_dR(M) (+) ...
# where the direct sums terminate when the index becomes negative.
#
# The PRIMARY part is the first term (non-S-image):
#    HC^n_primary(C^\infty(M)) = ker(d: Omega^n -> Omega^{n+1}) / (exact n-forms)
#                              = H^n_dR(M)  (when the Hodge decomp applies)
# So:
#    HC^n_primary(C^\infty(M)) = H^n_dR(M).
# For the Cartan of SU(2) (T^1 = S^1):
#    HC^2_primary(C^\infty(S^1)) = H^2_dR(S^1) = 0.

def dim_HC_n_total(r, n):
    """Total dimension of HC^n(C^\infty(T^r)) via Connes SBI.

    For smooth commutative: HC^n = sum_{k >= 0} H^{n-2k}_dR(M).
    """
    total = 0  # (local)
    k = 0      # (local)
    while n - 2 * k >= 0:
        total += h_dR_T_r(r, n - 2 * k)
        k += 1
    return total


def dim_HC_n_primary(r, n):
    """Primary HC^n dimension = HC^n / S(HC^{n-2}) = H^n_dR.

    Equivalently, the (non-S-image) new cocycle content at degree n.
    For a smooth manifold: HC^n_primary(C^\infty(M)) = H^n_dR(M).
    """
    return h_dR_T_r(r, n)


