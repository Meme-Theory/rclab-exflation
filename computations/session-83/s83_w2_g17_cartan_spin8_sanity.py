def sha256_of_file(path: Path) -> str:
    h = hashlib.sha256()                                               # (local)
    try:
        with open(path, "rb") as fh:
            while True:
                chunk = fh.read(65536)
                if not chunk:
                    break
                h.update(chunk)
    except OSError:
        return ""
    return h.hexdigest()


