def d_n_simple_roots(n: int) -> np.ndarray:
    """Return r=n x n matrix; rows are simple roots in the standard basis.

    D_n simple roots (Bourbaki): alpha_i = e_i - e_{i+1} for i=1..n-1,
                                 alpha_n = e_{n-1} + e_n.
    Each root has |alpha|^2 = 2, so all roots are long (D_n is simply-laced).
    """
    roots = np.zeros((n, n), dtype=np.float64)                         # (local) (n x n)
    for i in range(n - 1):
        roots[i, i] = 1.0
        roots[i, i + 1] = -1.0
    # Last simple root: e_{n-1} + e_n
    roots[n - 1, n - 2] = 1.0
    roots[n - 1, n - 1] = 1.0
    return roots


