def enumerate_weights(r: int, L_max: int) -> np.ndarray:
    """All integer vectors n in Z^r with Euclidean norm |n|_2 <= L_max.

    For r=4, L=8: |n|_inf cube is 17^4 = 83,521; sphere subset is smaller.
    For r=6, L=8: cube would be 17^6 = 24.1M — prohibitive. We enumerate
    on the sphere directly via an iterative inner-dimension recursion
    that prunes branches once partial sum-of-squares exceeds L^2.

    Substitution chain for cube cutoff:
      Step 1 (def): |n|_2 = sqrt(sum n_i^2); sphere = {n : |n|_2 <= L_max}.
      Step 2 (subst): |sphere| is the Ehrhart-type mode count of the ball.
      Step 3 (simpl): The sphere is a subset of the cube [-L, L]^r.
      Step 4 (direction): Using sphere preserves heat-kernel scaling of
                          the spectral sum at leading order; the spectral
                          cutoff |n|_2 <= L_max is the natural geometric
                          cutoff on the flat torus T^r (matches the Dirac
                          eigenvalue cutoff |lam_n| <= L_max).
    """
    # Iterative pruned enumeration via Python recursion; avoids 17^6 cube.
    Lsq = float(L_max) * float(L_max) + 1e-9                           # (local) L^2 cutoff + epsilon
    results = []                                                       # (local)
    partial = [0] * r                                                  # (local) reusable scratch buffer

    def recurse(depth: int, partial_sumsq: float) -> None:
        if depth == r:
            results.append(tuple(partial))                             # (local)
            return
        remaining = r - depth                                          # (local) remaining dims
        # Tight bound: each n_j in [-L, L] contributes n_j^2 >= 0, and we need
        #   partial_sumsq + n_d^2 + (remaining_zeros) <= Lsq.
        # Safe wide bound per coordinate: |n_d| <= sqrt(Lsq - partial_sumsq).
        max_abs = int(math.floor(math.sqrt(max(0.0, Lsq - partial_sumsq)) + 1e-12))  # (local)
        if max_abs > L_max:
            max_abs = L_max                                            # (local) also bounded by cube
        for n_d in range(-max_abs, max_abs + 1):
            new_sumsq = partial_sumsq + float(n_d) * float(n_d)        # (local)
            if new_sumsq <= Lsq:
                partial[depth] = n_d
                recurse(depth + 1, new_sumsq)

    recurse(0, 0.0)
    return np.array(results, dtype=np.float64)


def dirac_spectrum_T_r(weights: np.ndarray, phi: float, alpha: np.ndarray,
                       clifford_mult: int) -> tuple[np.ndarray, np.ndarray]:
    """On T^r Cartan, Dirac spectrum at deformation phi along simple root alpha.

    Returns (|lam|, multiplicity) arrays.

    SUBSTITUTION CHAIN:
      Step 1 (def): D_phi |n> = (n + phi * alpha) . gamma |n>
                    where gamma = (gamma^1, ..., gamma^r) are Clifford generators.
      Step 2 (subst): D_phi^2 |n> = |n + phi * alpha|^2 * identity  (Clifford)
      Step 3 (direction): eigenvalues of |D_phi| on weight n are
                          |lam_n(phi)| = sqrt( sum_i (n_i + phi * alpha_i)^2 )
                          with Clifford multiplicity 2^{floor(r/2)} per weight.
    """
    shifted = weights + phi * alpha[None, :]                           # (local)
    abs_lam = np.sqrt(np.sum(shifted * shifted, axis=1))               # (local)
    mult = np.full(len(weights), clifford_mult, dtype=np.int64)        # (local)
    return abs_lam, mult


def spectral_moments(abs_lam: np.ndarray, mult: np.ndarray,
                     cutoff: float) -> dict:
    """Compute SDW, zeta2, zeta4 spectral moments per S80 convention.

      SDW   = sum d_n * |lam_n|      (Selberg dimension-weighted)
      zeta2 = sum d_n * 1 / |lam_n|^2
      zeta4 = sum d_n * 1 / |lam_n|^4

    Zero modes (|lam| <= cutoff) are excluded to avoid 1/0.
    """
    nz = abs_lam > cutoff                                              # (local)
    lam = abs_lam[nz]                                                  # (local)
    m = mult[nz].astype(np.float64)                                    # (local)
    return {
        "SDW":   float(np.sum(m * lam)),
        "zeta2": float(np.sum(m / (lam * lam))),
        "zeta4": float(np.sum(m / (lam ** 4))),
    }


# ============================================================================
# Section 5: Compute J_u1^{f}(L) via 5-pt central FD in phi
# ============================================================================

def stencil_5pt(v_m2: float, v_m1: float, v_0: float,
                v_p1: float, v_p2: float, h: float) -> float:
    """5-pt central FD for 2nd derivative. Standard coefficients
       (-1, +16, -30, +16, -1)/(12 h^2).
    """
    return (-v_m2 + 16.0 * v_m1 - 30.0 * v_0 + 16.0 * v_p1 - v_p2) / (12.0 * h ** 2)


def compute_J_branch(weights: np.ndarray, alpha: np.ndarray,
                     clifford_mult: int, h: float, cutoff: float) -> dict:
    """J_u1^{f}(L) = d^2 / dphi^2 [ sum d_n f(|lam_n(phi)|) ] at phi=0.

    Returns {"SDW": J_SDW, "zeta2": J_zeta2, "zeta4": J_zeta4}.
    """
    phi_vals = (-2 * h, -h, 0.0, h, 2 * h)                             # (local)
    traces = {"SDW": np.zeros(5), "zeta2": np.zeros(5), "zeta4": np.zeros(5)}
    for k, phi in enumerate(phi_vals):
        abs_lam, mult = dirac_spectrum_T_r(weights, phi, alpha, clifford_mult)
        m = spectral_moments(abs_lam, mult, cutoff)
        for fn in ("SDW", "zeta2", "zeta4"):
            traces[fn][k] = m[fn]
    out = {}
    for fn in ("SDW", "zeta2", "zeta4"):
        out[fn] = stencil_5pt(*traces[fn], h)
    return out


def drift_u1_for_group(rank: int, L_max: int, h: float,
                       cutoff: float) -> dict:
    """Compute drift_u1 for the Cartan T^r of a rank-r compact simple group.

    For each of the r simple roots (read from D_n or analogous family),
    compute alpha_1^L = J^{zeta2}/J^{SDW}. Cross-root mean is the "exact"
    reference for drift_u1 per S80 W2C convention.
    """
    weights = enumerate_weights(rank, L_max)                           # (local)
    N_modes = len(weights)                                             # (local)
    clifford_mult = 2 ** (rank // 2)                                   # (local) spinor dim per weight

    # All D_n simple roots (standard Bourbaki normalization, |alpha|^2 = 2)
    roots = d_n_simple_roots(rank)                                     # (local) (r, r)

    J_per_root = []                                                    # (local)
    alpha1_per_root = []                                               # (local)
    for i in range(rank):
        alpha_i = roots[i]                                             # (local) i-th simple root
        J = compute_J_branch(weights, alpha_i, clifford_mult, h, cutoff)
        J_per_root.append(J)
        if abs(J["SDW"]) > 1e-30:
            a1 = J["zeta2"] / J["SDW"]                                 # (local)
        else:
            a1 = np.nan                                                # (local) degenerate
        alpha1_per_root.append(a1)

    alpha1_arr = np.array(alpha1_per_root)                             # (local)
    alpha1_exact = float(np.nanmean(alpha1_arr))                       # (local) cross-root mean
    # Use the FIRST simple root as the "u1 branch" probe (convention)
    alpha1_u1 = float(alpha1_arr[0])                                   # (local)
    if abs(alpha1_exact) > 1e-30:
        drift_u1 = abs(alpha1_u1 - alpha1_exact) / abs(alpha1_exact)   # (local)
    else:
        drift_u1 = np.nan                                              # (local)

    return {
        "rank": rank,
        "L_max": L_max,
        "N_modes": N_modes,
        "clifford_mult": clifford_mult,
        "alpha1_per_root": alpha1_arr,
        "alpha1_exact": alpha1_exact,
        "alpha1_u1": alpha1_u1,
        "drift_u1": drift_u1,
        "J_per_root": J_per_root,
    }


