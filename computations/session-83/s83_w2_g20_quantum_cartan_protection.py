def h_dR_S1(n):
    """de Rham cohomology of the circle S^1 in degree n.

    Connes-HKR base case: smooth 1-manifold.
        H^0_dR(S^1) = C (constants)
        H^1_dR(S^1) = C (generator d(theta))
        H^n_dR(S^1) = 0 for n >= 2 (trivially, no n-forms on 1D manifold)
    """
    if n == 0:
        return 1
    if n == 1:
        return 1
    return 0


# ---------------------------------------------------------------------------
# Section 6 — Hochschild complex on C[K, K^{-1}] truncated to Laurent span
# ---------------------------------------------------------------------------
#
# We model the Cartan U_q(h) = C[K, K^{-1}] by truncating Laurent polynomials
# to span{K^n : n in [-N, N]}. Hochschild homology/cohomology of this
# commutative polynomial algebra at any q (since [K, K] = 0) matches the
# classical HKR computation.
#
# Hochschild differential (for commutative algebra, cyclic version):
#   b(a_0 o a_1 o a_2) = a_0 a_1 o a_2 - a_0 o a_1 a_2 + a_2 a_0 o a_1
# where o = tensor product.
#
# For a commutative algebra over C, HH^n(A) ~ Omega^n_{A/C} (HKR).
# Here A = C[K, K^{-1}] ~ O(G_m) ~ C[t, t^{-1}].
# Omega^n_{A/C} = A dK^{\wedge n} / relations. For n >= 2, dK \wedge dK = 0
# so Omega^n = 0 for n >= 2. This is the algebraic analog of the smooth
# H^n_dR(S^1) = 0 result.

def dim_Omega_n_Laurent(N, n):
    """Dimension of algebraic n-forms Omega^n_{C[K,K^{-1}]/C} in truncation.

    For commutative polynomial algebra in 1 variable (or Laurent):
        Omega^0 = A                     (dim = 2N+1 in truncation)
        Omega^1 = A dK                  (dim = 2N+1)
        Omega^n = 0 for n >= 2
    """
    if n == 0:
        return 2 * N + 1
    if n == 1:
        return 2 * N + 1
    return 0


def dim_HH_n_Cartan(N, n, q=None):
    """Hochschild cohomology HH^n(C[K,K^{-1}]) in truncation N.

    By HKR: HH^n = Omega^n for commutative smooth algebras.
    The result is INDEPENDENT of q: the Cartan U_q(h) is commutative
    for all q (K commutes with itself), so the algebra structure does
    not depend on q. q only matters for E, F generators, not the Cartan.
    """
    _ = q  # noqa: explicit acknowledgment that q is irrelevant for Cartan
    return dim_Omega_n_Laurent(N, n)


def dim_HC_n_Cartan(N, n, q=None):
    """Cyclic cohomology HC^n(C[K, K^{-1}]) in truncation N.

    Connes' SBI long exact sequence for smooth commutative M:
        HC^n(C^inf(M)) = ker(d: Omega^n -> Omega^{n+1})
                         (+) H^{n-2}_dR(M) (+) H^{n-4}_dR(M) (+) ...

    For M = S^1 (or Laurent algebra):
        n=0: ker(d: Omega^0 -> Omega^1) + {nothing below} = H^0_dR = 1
        n=1: ker(d: Omega^1 -> Omega^2) + H^{-1}_dR
             = Omega^1 (since d: Omega^1 -> 0 is zero) + 0
             = 1 (after taking H^1_dR; see below)
             [Correction: in the non-periodic reduced case,
              HC^1 = H^1_dR = 1.]
        n=2: ker(d: Omega^2 -> Omega^3) + H^0_dR
             = 0 + 1 = 1   [TOTAL, all from S-image]
        n=2 PRIMARY = HC^2 / S(HC^0) = 1 - 1 = 0

    The KEY QUANTITY for R-protection is the PRIMARY part at n=2.
    """
    _ = q  # (noqa) q-independence of Cartan
    if n == 0:
        return h_dR_S1(0)   # 1
    if n == 1:
        return h_dR_S1(1)   # 1
    if n == 2:
        # total HC^2 = H^2_dR(S^1) + S(HC^0) = 0 + 1 = 1
        return h_dR_S1(2) + h_dR_S1(0)
    if n == 3:
        return h_dR_S1(3) + h_dR_S1(1)
    return 0


def dim_HC_n_Cartan_primary(N, n, q=None):
    """Primary part of HC^n: HC^n / S(HC^{n-2}).

    This isolates the NON-TRIVIAL cocycle content (the part not already
    accounted for by lower-degree cocycles via the S-periodicity map).
    For R-protection, this is what must vanish at n=2.
    """
    _ = q
    if n == 0:
        return dim_HC_n_Cartan(N, 0)
    if n == 1:
        return dim_HC_n_Cartan(N, 1)
    if n >= 2:
        # primary = total - S-image from HC^{n-2}
        return dim_HC_n_Cartan(N, n) - dim_HC_n_Cartan(N, n - 2)
    return 0


# ---------------------------------------------------------------------------
# Section 7 — Full NC torus HC^2 for contrast (sanity check)
# ---------------------------------------------------------------------------
#
# The irrational non-commutative torus A_theta has
#    HC^2_total(A_theta) = 2 (symplectic class + S-image of HC^0)
#    HC^2_primary(A_theta) = 1 (symplectic class, NOT in S-image)
# This shows the PULLBACK distinction: the full algebra has a non-trivial
# primary 2-cocycle; the Cartan subfactor does not.

def dim_HC2_primary_NC_torus(theta):
    """HC^2_primary dimension of irrational NC torus A_theta.

    Connes 1980 (C*-algebres et geom diff):
      A_theta = C*(<U, V> : UV = exp(2 pi i theta) VU)
      For theta irrational: H^2_dR-like class survives.
      HC^2_primary(A_theta_irrational) = 1 (the symplectic cocycle).

    For theta = 0 (commutative T^2): HC^2_primary = H^2_dR(T^2) = 1
      (still 1-dim; it's the volume form).
    """
    if abs(theta - round(theta)) < 1e-12:
        # theta integer -> commutative torus T^2
        return 1  # H^2_dR(T^2) = 1
    # irrational -> NC torus, symplectic class survives
    return 1


def dim_HC2_primary_pullback_S1(theta):
    """Pullback of HC^2 from NC torus A_theta via S^1 -> T^2 inclusion.

    Map i: C(S^1) -> A_theta, i(f)(U, V) = f(U) (first coordinate).
    Dually: i*: HC^2(A_theta) -> HC^2(C(S^1)).

    The symplectic 2-cocycle phi_symp on A_theta:
      phi_symp(a, b, c) = tau(a . [d_1 b, d_2 c])
    where d_1 = U d/dU, d_2 = V d/dV, tau = normalized trace.

    Under i, elements have form i(f) = f(U) only. So d_2 i(f) = 0
    (no V-dependence). Thus phi_symp(i(a), i(b), i(c)) = 0 for all
    a, b, c in C(S^1).

    => i*(HC^2_primary(A_theta)) = 0 in HC^2(C(S^1)).
    """
    _ = theta  # pullback kills symplectic class INDEPENDENT of theta
    return 0


# ---------------------------------------------------------------------------
# Section 8 — Verification via simplicial S^1 and Mayer-Vietoris
# ---------------------------------------------------------------------------
#
# Independent check: triangulate S^1 by 2 vertices + 2 edges, compute
# simplicial cohomology H^*_simp(S^1). Compare to H^*_dR via de Rham
# theorem. This gives an integer-valued cross-check.

def simplicial_H_S1(n):
    """Simplicial cohomology H^n_simp(S^1; Z) -> rank over C.

    Triangulation: S^1 = 2 vertices (v_0, v_1) + 2 edges (e_{01}, e_{10}).
    Cochain complex: C^0 = Z^2, C^1 = Z^2, C^n = 0 for n >= 2.
    Coboundary d: C^0 -> C^1, d(f)(e_{ij}) = f(v_j) - f(v_i).
    In matrix form (bases (v_0, v_1), (e_{01}, e_{10})):
        d = [[-1, 1], [1, -1]]
    rank(d) = 1.
        H^0 = ker(d)/0 = 2 - 1 = 1
        H^1 = C^1 / im(d) = 2 - 1 = 1
        H^n = 0 for n >= 2.
    Matches de Rham.
    """
    if n == 0:
        return 1
    if n == 1:
        return 1
    return 0


def build_coboundary_matrix():
    """Build simplicial coboundary d: C^0(S^1) -> C^1(S^1)."""
    d = np.array([[-1.0, 1.0], [1.0, -1.0]], dtype=np.float64)  # (local)
    return d


def compute_H_from_coboundary(d_matrix):
    """Compute H^0 = dim(ker(d_matrix)), H^1 = dim(coker(d_matrix))."""
    rank = np.linalg.matrix_rank(d_matrix, tol=EPS_ZERO)   # (local)
    m, n = d_matrix.shape                                  # (local)
    h0 = n - rank                                           # (local) dim ker
    h1 = m - rank                                           # (local) dim coker
    return h0, h1, rank


