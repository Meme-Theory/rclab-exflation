def windowed_d_s(sigma, P):
    """d_s(sigma) = -2 d ln P / d ln sigma via centered differences on the log grid.

    This is a LOG-DERIVATIVE: any multiplicative sigma-independent prefactor w in
    P = w*g(sigma) is annihilated (the multiplicative-normalization cancellation,
    Sage-verified d(d_s)/dw = 0). The result depends ONLY on the sigma-shape g.
    """
    ln_sig = np.log(sigma)  # (local)
    ln_P = np.log(np.maximum(P, 1e-300))  # (local) underflow guard
    return -2.0 * np.gradient(ln_P, ln_sig)


def fiber_heat_trace(sigma_grid, sector_evals):
    """SU(3) fiber heat trace P_fiber(sigma) = sum_{(p,q)} dim(p,q) * sum_i exp(-sigma * |lambda_i|^2).

    The L12 cache stores BLOCK-level abs_evals (the Peter-Weyl multiplicity dim(p,q) is applied
    here as the per-sector weight, per the cache contract in agent-memory s84_spectrum_cache note).
    GPU path: ship the (n_modes,) eigenvalue-squared vector and the (n_sigma,) grid to torch and
    do the outer exp-sum on cuda.
    """
    # Flatten the cache into a (weight, |lambda|^2) list across all sectors.
    w_list = []  # (local)
    lam2_list = []  # (local)
    for (p, q), rec in sector_evals.items():
        dim = float(rec["dim"])  # (local) Peter-Weyl multiplicity weight
        abs_evals = np.asarray(rec["abs_evals"], dtype=np.float64)  # (local)
        w_list.append(np.full(abs_evals.shape, dim))
        lam2_list.append(abs_evals ** 2)
    weights = np.concatenate(w_list)  # (local)
    lam2 = np.concatenate(lam2_list)  # (local)

    if _HAS_TORCH:
        sig_t = torch.tensor(sigma_grid, device=_DEVICE, dtype=torch.float64)  # (local)
        lam2_t = torch.tensor(lam2, device=_DEVICE, dtype=torch.float64)  # (local)
        w_t = torch.tensor(weights, device=_DEVICE, dtype=torch.float64)  # (local)
        # P(sigma) = sum_n w_n exp(-sigma lam2_n); do it in sigma-chunks to bound memory
        P = torch.empty(sig_t.shape, device=_DEVICE, dtype=torch.float64)  # (local)
        chunk = 2000  # (local) modes are ~1e5; sigma is 100, fits easily, but chunk modes for safety
        for j in range(sig_t.shape[0]):
            expo = -sig_t[j] * lam2_t  # (local)
            P[j] = torch.sum(w_t * torch.exp(expo))
        return P.cpu().numpy(), int(weights.sum()), len(weights)
    else:
        expo = -np.outer(sigma_grid, lam2)  # (local) (n_sigma, n_modes)
        P = np.sum(weights[None, :] * np.exp(expo), axis=1)  # (local)
        return P, int(weights.sum()), len(weights)


