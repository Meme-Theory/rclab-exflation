# a0/a2|_orb / a0/a2|_full = f_a0(T=0) / f_a2(T=0)
# where f_ak(T=0) = sum_{T=0} a_k / sum_all a_k
# Since T=1 and T=2 are exactly equal:
# f_ak(T=0) = a_k(T=0) / [a_k(T=0) + 2 * a_k(T=1)]
# The ratio changes only if a_k(T=0) / a_k(T=1) differs between k=0 and k=2.

